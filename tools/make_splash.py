#!/usr/bin/env python3
"""Converts Jamie's 'Twisted Tracker' graffiti logo into the Tracker+ splash bitmap:
720x396, 256-colour palette (FT812 PALETTED565), written as a C++ source file."""
import sys
from PIL import Image, ImageChops
W, H = 720, 396
src, out_dir = sys.argv[1], sys.argv[2]
im = Image.open(src).convert('RGB')
bg = Image.new('RGB', im.size, (255, 255, 255))
mask = ImageChops.difference(im, bg).convert('L').point(lambda v: 255 if v > 18 else 0)
x0, y0, x1, y1 = mask.getbbox()
m = 8
im = im.crop((max(0, x0 - m), max(0, y0 - m), min(im.width, x1 + m), min(im.height, y1 + m)))
s = min(W / im.width, H / im.height)
im = im.resize((round(im.width * s), round(im.height * s)), Image.LANCZOS)
can = Image.new('RGB', (W, H), (255, 255, 255))
can.paste(im, ((W - im.width) // 2, (H - im.height) // 2))
q = can.quantize(256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
idx = q.tobytes()
pal = q.getpalette()[:768]
pal += [255] * (768 - len(pal))
q.convert('RGB').save(out_dir + '/twisted_splash_preview.png')

def rows(data, per=24):
    return ",\n".join("    " + ", ".join(data[i:i + per]) for i in range(0, len(data), per))

pal565 = []
for i in range(256):
    r, g, b = pal[3 * i:3 * i + 3]
    v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    pal565 += [f"0x{v & 0xFF:02X}", f"0x{v >> 8:02X}"]   # little endian, as RAM_G wants it

h = f"""#pragma once
// Twisted: the 'Twisted Tracker' graffiti splash (Tracker+ only). Generated by tools/make_splash.py.
#include <stdint.h>

#if defined(PLATFORM_IMX) && !defined(TRACKER_MINI)
#define TWISTED_SPLASH 1
#endif

constexpr uint16_t kTwistedSplashW = {W};
constexpr uint16_t kTwistedSplashH = {H};
extern const uint8_t twisted_splash_idx[{W * H}];  // PALETTED565 indices
extern const uint8_t twisted_splash_pal[512];      // RGB565 palette, little endian
// where it goes in the FT812's RAM_G: after the controls' display lists (150000 + 65 x 8192)
constexpr uint32_t kTwistedSplashRamAddr = 690000;
constexpr uint32_t kTwistedSplashPalAddr = kTwistedSplashRamAddr + 285184; // 4-byte aligned, after the pixels
"""
c = ('#include "twisted_splash.h"\n#ifdef TWISTED_SPLASH\n\n'
     f'const uint8_t twisted_splash_pal[512] = {{\n{rows(pal565)}\n}};\n\n'
     f'const uint8_t twisted_splash_idx[{W * H}] = {{\n{rows([str(b) for b in idx], 40)}\n}};\n\n#endif\n')
open(out_dir + '/twisted_splash.h', 'w').write(h)
open(out_dir + '/twisted_splash.cpp', 'w').write(c)
print("ok", len(idx))
